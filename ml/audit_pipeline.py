def populate_official_yamnet_labels(class_map_src=None):
    """
    Downloads official YAMNet 521 class map CSV and creates yamnet_labels.txt.
    """
    import urllib.request
    url = "https://raw.githubusercontent.com/tensorflow/models/master/research/audioset/yamnet/yamnet_class_map.csv"
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req) as resp:
            csv_content = resp.read().decode('utf-8')
    except Exception as e:
        print(f"[audit] Warning: could not download via URL ({e}), falling back to local source.")
        with open(class_map_src, "r", encoding="utf-8") as f:
            csv_content = f.read()

    import io
    labels = []
    reader = csv.DictReader(io.StringIO(csv_content))
    for row in reader:
        if "display_name" in row and row["display_name"]:
            labels.append(row["display_name"].strip('"'))
            
    if len(labels) != 521:
        raise ValueError(f"Expected 521 AudioSet labels, found {len(labels)}")
        
    for target_dir in ["ml/exported", "app/src/main/assets/models"]:
        os.makedirs(target_dir, exist_ok=True)
        txt_path = os.path.join(target_dir, "yamnet_labels.txt")
        with open(txt_path, "w", encoding="utf-8") as out_f:
            for l in labels:
                out_f.write(l + "\n")
                
        csv_path = os.path.join(target_dir, "yamnet_class_map.csv")
        with open(csv_path, "w", encoding="utf-8") as out_csv:
            out_csv.write(csv_content)
                
    print(f"[audit] Successfully populated official 521 YAMNet AudioSet labels in ml/exported/ and app/src/main/assets/models/")
    return labels

