def run_source_split_and_hash_audit():
    print("\n================================================================================")
    print(" 2. SOURCE-LEVEL SPLIT & SHA-256 INTEGRITY AUDIT")
    print("================================================================================")
    inventory = build_source_inventory()
    rng = np.random.RandomState(RANDOM_SEED)
    
    train_sources, val_sources, test_sources = [], [], []
    for c_idx in range(4):
        class_sources = [s for s in inventory if s["class_idx"] == c_idx]
        rng.shuffle(class_sources)
        n_c = len(class_sources)
        n_train = int(0.70 * n_c)
        n_val = int(0.15 * n_c)
        train_sources.extend(class_sources[:n_train])
        val_sources.extend(class_sources[n_train:n_train + n_val])
        test_sources.extend(class_sources[n_train + n_val:])
        
    train_ids = set(s["source_id"] for s in train_sources)
    val_ids = set(s["source_id"] for s in val_sources)
    test_ids = set(s["source_id"] for s in test_sources)
    
    overlap_train_val = train_ids.intersection(val_ids)
    overlap_train_test = train_ids.intersection(test_ids)
    overlap_val_test = val_ids.intersection(test_ids)
    
    print(f"Source Counts: Train={len(train_sources)}, Val={len(val_sources)}, Test={len(test_sources)}")
    print(f"Split Overlap Verification:")
    print(f"  - Train intersect Val Overlap:  {len(overlap_train_val)} (Expected: 0)")
    print(f"  - Train intersect Test Overlap: {len(overlap_train_test)} (Expected: 0)")
    print(f"  - Val intersect Test Overlap:   {len(overlap_val_test)} (Expected: 0)")
    assert len(overlap_train_val) == 0 and len(overlap_train_test) == 0 and len(overlap_val_test) == 0
    
    # Hash check: compute SHA-256 for all 230 raw generated audio waveforms
    hashes = {}
    duplicate_count = 0
    for s in inventory:
        audio = generate_source_audio(s["class_idx"], s["subtype"], np.random.RandomState(s["source_id"] + 1000))
        h = hashlib.sha256(audio.tobytes()).hexdigest()
        if h in hashes:
            duplicate_count += 1
        hashes[h] = s["source_id"]
        
    print(f"SHA-256 Waveform Uniqueness: {len(hashes)} unique hashes across {len(inventory)} sources ({duplicate_count} duplicates).")
    assert duplicate_count == 0, "Duplicate audio detected!"
    print("Source-level isolation & waveform uniqueness: VERIFIED 100% CLEAN.")

