def run_yamnet_model_audit():
    print("\n================================================================================")
    print(" 4. YAMNET MODEL & EMBEDDING TENSOR AUDIT")
    print("================================================================================")
    yamnet_path = "ml/exported/yamnet.tflite"
    interp = tf.lite.Interpreter(model_path=yamnet_path)
    interp.allocate_tensors()
    
    input_details = interp.get_input_details()
    output_details = interp.get_output_details()
    
    print(f"YAMNet File:        {yamnet_path} ({os.path.getsize(yamnet_path)} bytes)")
    print(f"Input Name:         {input_details[0]['name']}")
    print(f"Input Shape:        {input_details[0]['shape']} (Expected: [15600] 16kHz float32 waveform)")
    print(f"Input Dtype:        {input_details[0]['dtype']}")
    print(f"Output 0 (Scores):  {output_details[0]['name']} | shape: {output_details[0]['shape']} (521 AudioSet classes)")
    
    # Locate 1024-D embedding tensor dynamically
    embedding_tensor_idx = None
    embedding_tensor_name = None
    for d in interp.get_tensor_details():
        shape = list(d["shape"])
        if shape == [1, 1024] and "flatten" in d["name"].lower():
            embedding_tensor_idx = d["index"]
            embedding_tensor_name = d["name"]
            break
            
    print(f"Penultimate Embedding Tensor:")
    print(f"  - Dynamic Index:  {embedding_tensor_idx}")
    print(f"  - Tensor Name:    {embedding_tensor_name}")
    print(f"  - Shape:          [1, 1024] float32")
    assert embedding_tensor_idx == 123, f"Expected index 123 in this flatbuffer, got {embedding_tensor_idx}"
    print("YAMNet 1024-D Embedding Extraction: VERIFIED.")

